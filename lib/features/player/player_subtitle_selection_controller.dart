import 'package:media_kit/media_kit.dart';

import 'player_subtitle_selection.dart';

/// Keeps automatic selection separate from mpv's currently selected track.
/// All writes are serialized so a late automatic choice cannot undo a manual one.
class SubtitleSelectionController {
  SubtitleSelectionController({required this.setTrack});

  final Future<void> Function(SubtitleTrack track) setTrack;
  Future<void> _tail = Future.value();
  List<SubtitleTrack> _tracks = const [];
  bool _automatic = true;
  bool _active = false;
  bool _disposed = false;
  int _revision = 0;
  SubtitleTrack? _target;
  String? _fallbackTracks;

  bool get automatic => _automatic;

  /// Drain any in-flight write before opening another media file.
  Future<void> reset() {
    _revision++;
    _automatic = true;
    _active = false;
    _tracks = const [];
    _target = null;
    _fallbackTracks = null;
    return _tail;
  }

  Future<void> activate(List<SubtitleTrack> tracks) {
    if (_disposed) return Future.value();
    final first = !_active;
    _active = true;
    _tracks = List.of(tracks);
    return _selectAutomatic(force: first);
  }

  Future<void> updateTracks(List<SubtitleTrack> tracks) {
    _tracks = List.of(tracks);
    return _selectAutomatic();
  }

  Future<void> select(SubtitleTrack track) {
    if (_disposed) return Future.value();
    _automatic = track.id == 'auto';
    if (_automatic) return _selectAutomatic(force: true);
    _fallbackTracks = null;
    return _enqueue(track);
  }

  Future<void> _selectAutomatic({bool force = false}) {
    if (_disposed || !_active || !_automatic) return Future.value();
    final preferred = preferredChineseSubtitle(_tracks);
    final target = preferred ?? SubtitleTrack.auto();
    // Re-run mpv fallback when new non-Chinese tracks arrive, but not for the
    // track-list events generated by selecting the same set of tracks.
    final fallbackTracks = preferred == null
        ? _tracks.map((track) => (track.id, track.uri, track.data)).join('|')
        : null;
    if (!force && target == _target && fallbackTracks == _fallbackTracks) {
      return Future.value();
    }
    _fallbackTracks = fallbackTracks;
    return _enqueue(target);
  }

  Future<void> _enqueue(SubtitleTrack track) {
    final revision = ++_revision;
    _target = track;
    final next = _tail.then((_) async {
      if (_disposed || revision != _revision) return;
      await setTrack(track);
    });
    _tail = next.catchError((Object _) {
      if (revision == _revision) _target = null;
    });
    return next;
  }

  void dispose() {
    _disposed = true;
    _revision++;
  }
}
